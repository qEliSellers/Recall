export const ACELLUS_COURSES: CatalogCourse[] = courses.map((course) => ({
  ...course,
  catalogUrl: ACELLUS_CATALOG_URL,
  verifiedAt: CATALOG_VERIFIED_AT,
  unitsVerified: course.units.length > 0,
}));

export function getCatalogCourse(id: string): CatalogCourse | undefined {
  return ACELLUS_COURSES.find((course) => course.id === id);
}

export function getCatalogSubjects(): string[] {
  return [...new Set(ACELLUS_COURSES.map((course) => course.subject))];
}
